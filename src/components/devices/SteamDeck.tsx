interface PressableMeshProps {
  control: SteamDeckControl
  meshes: MeshSlot[]
  position: [number, number, number]
  /**
   * How far the mesh depresses on click. Increases pre-rotation Y, which after the
   * outer -90°X rotation maps to world -Z (away from camera = pressing INTO the
   * gamepad face since the camera views the face from in front).
   */
  pressDepth?: number
  onControlEvent?: (event: SteamDeckControlEvent) => void
}

function PressableMesh({
  control,
  meshes,
  position,
  pressDepth = 0.04,
  onControlEvent,
}: PressableMeshProps) {
  const [pressed, setPressed] = useState(false)
  const emit = (type: SteamDeckControlEvent['type']) =>
    emitSimpleControl(onControlEvent, control, `real-${control}`, type)

  // Press INTO the gamepad face. After -90°X outer rotation, pre-Y+ => world Z- (away from camera).
  const y = pressed ? position[1] + pressDepth : position[1]

  return (
    <group
      position={[position[0], y, position[2]]}
      onPointerOver={() => { document.body.style.cursor = 'pointer' }}
      onPointerOut={(event) => {
        releasePointerCaptureSafely(event)
        document.body.style.cursor = 'auto'
        if (pressed) { setPressed(false); emit('up') }
      }}
      onPointerDown={(event) => {
        event.stopPropagation()
        setPointerCaptureSafely(event)
        setPressed(true)
        emit('down')
      }}
      onPointerUp={(event) => {
        event.stopPropagation()
        releasePointerCaptureSafely(event)
        setPressed(false)
        emit('up')
      }}
    >
      {meshes.map((m, i) => (
        <mesh key={i} geometry={m.geometry} material={m.material} />
      ))}
    </group>
  )
}

