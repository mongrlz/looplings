function RealStick({ control, tiltMeshes, fixedMeshes = [], position, onControlEvent }: RealStickProps) {
  const [dragging, setDragging] = useState(false)
  const [vector, setVector] = useState({ x: 0, y: 0 })
  const groupRef = useRef<THREE.Group>(null)
  const { camera, gl } = useThree()
  const onControlEventRef = useRef(onControlEvent)
  useEffect(() => { onControlEventRef.current = onControlEvent }, [onControlEvent])

  const TILT_MAX = 0.25
  const DRAG_RADIUS = 0.3

  // Window-level drag: project mouse ray onto virtual plane at stick position.
  // Capture-phase listeners block OrbitControls during drag.
  useEffect(() => {
    if (!dragging) return
    const domElement = gl.domElement

    const onPointerMove = (e: PointerEvent) => {
      e.stopPropagation()
      if (!groupRef.current) return
      const stickWorld = new THREE.Vector3()
      groupRef.current.getWorldPosition(stickWorld)

      const rect = domElement.getBoundingClientRect()
      const ndc = new THREE.Vector2(
        ((e.clientX - rect.left) / rect.width) * 2 - 1,
        -((e.clientY - rect.top) / rect.height) * 2 + 1
      )
      const ray = new THREE.Raycaster()
      ray.setFromCamera(ndc, camera)

      const camDir = camera.getWorldDirection(new THREE.Vector3())
      const plane = new THREE.Plane().setFromNormalAndCoplanarPoint(camDir.clone().negate(), stickWorld)
      const hit = new THREE.Vector3()
      if (!ray.ray.intersectPlane(plane, hit)) return

      const local = groupRef.current.worldToLocal(hit)
      const next = {
        x: clamp(local.x / DRAG_RADIUS, -1, 1),
        y: clamp(local.z / DRAG_RADIUS, -1, 1),
      }
      setVector(next)
      onControlEventRef.current?.({
        control,
        mesh: control,
        type: 'move',
        uv: null,
        value: next,
      })
    }

    const onPointerUp = (e: PointerEvent) => {
      e.stopPropagation()
      document.body.style.cursor = 'auto'
      setDragging(false)
      setVector({ x: 0, y: 0 })
      onControlEventRef.current?.({
        control,
        mesh: control,
        type: 'up',
        uv: null,
        value: { x: 0, y: 0 },
      })
    }

    domElement.addEventListener('pointermove', onPointerMove, true)
    domElement.addEventListener('pointerup', onPointerUp, true)
    return () => {
      domElement.removeEventListener('pointermove', onPointerMove, true)
      domElement.removeEventListener('pointerup', onPointerUp, true)
    }
  }, [dragging, camera, gl, control])

  // Fixed meshes (base ring) sit at the anchor position but never tilt.
  // Tilt meshes (stem + cap) rotate with the stick vector.
  // groupRef tracks the tilting group so worldToLocal projects correctly.
  return (
    <group position={position}>
      {/* BASE — stays locked to the gamepad body */}
      {fixedMeshes.map((m, i) => (
        <mesh key={`fixed-${i}`} geometry={m.geometry} material={m.material} />
      ))}

      {/* STEM + CAP — tilts with user drag */}
      <group ref={groupRef} rotation={[-vector.y * TILT_MAX, 0, -vector.x * TILT_MAX]}>
        <group
          onPointerOver={() => { document.body.style.cursor = 'grab' }}
          onPointerOut={() => { if (!dragging) document.body.style.cursor = 'auto' }}
          onPointerDown={(event) => {
            event.stopPropagation()
            document.body.style.cursor = 'grabbing'
            setDragging(true)
            onControlEvent?.({
              control,
              mesh: control,
              type: 'down',
              uv: null,
              value: { x: 0, y: 0 },
            })
          }}
        >
          {tiltMeshes.map((m, i) => (
            <mesh key={`tilt-${i}`} geometry={m.geometry} material={m.material} />
          ))}
        </group>
      </group>
    </group>
  )
}

